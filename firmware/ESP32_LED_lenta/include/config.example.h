#ifndef CONFIG_H
#define CONFIG_H

// ---- Лента WS2812B (адресуемая) ----
#define LED_PIN 27         // DATA-пин ленты
#define NUM_LEDS 60        // количество диодов в ленте
#define LED_BRIGHTNESS 100 // общая яркость 0..255

// ---- Ультразвуковой датчик HC-SR04 ----
#define TRIG_PIN 13
#define ECHO_PIN 12
#define SOUND_SPEED_DIV 58.0 // мкс -> см (340 м/с)

// ---- Диапазон расстояния (см) ----
#define MAX_DIST 150.0 // дальше этого — лента погашена
#define MIN_DIST 3.0   // ближе этого — вся лента красная

// Сглаживание расстояния (0..1, меньше = плавнее)
#define SMOOTHING 0.3
// Сглаживание числа горящих диодов (0..1, меньше = плавнее)
#define SMOOTHING_LIT 0.3
// Число замеров для медианного фильтра (нечётное!)
#define SAMPLES 3
// Пауза между замерами, мс (даём датчику успокоиться)
#define SAMPLE_DELAY 10
// Дальше этого — считаем "нет отражения" и держим прошлое значение
#define MAX_VALID_DIST 300.0

#endif
