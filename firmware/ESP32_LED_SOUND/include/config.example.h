// config.example.h
// ============================================================
//  ПРИМЕР конфигурации проекта ESP32_LED_SOUND (БЕЗ секретов).
//
//  Как использовать:
//   1. Скопируй в config.h:  cp include/config.example.h include/config.h
//   2. При необходимости подправь пины/параметры под своё железо.
//
//  ВАЖНО: config.h в git НЕ попадает (.gitignore),
//  а этот пример — попадает, чтобы проект можно было клонировать.
// ============================================================

#ifndef CONFIG_H
#define CONFIG_H

// ---- Лента WS2812B (адресуемая) ----
#define LED_PIN 27         // DATA-пин ленты
#define NUM_LEDS 60        // количество диодов в ленте
#define LED_BRIGHTNESS 100 // общая яркость 0..255

// ---- Звуковой датчик (цифровой, 3 пина: SIG / VCC / GND) ----
#define SOUND_PIN 14       // пин SIG датчика -> GPIO ESP32
// ВАЖНО: питай датчик от 3.3В, тогда SIG безопасен для ESP32 (3.3В).
// Если питаешь от 5В — поставь делитель 1k+2k на SIG, иначе ESP32 сгорит.

// ---- Настройки реакции на звук ----
#define WINDOW_MS 250   // окно подсчёта "битов/хлопков" (мс)
#define MAX_BEATS 8     // столько срабатываний за окно = вся лента горит
#define SMOOTH 0.25     // сглаживание (меньше = плавнее и медленнее)
#define DEBOUNCE_MS 30  // антидребезг: игнорируем повторы короче этого (мс)

#endif
